export const videosById = Object.fromEntries(videos.map((v) => [v.id, v])) as Record<string, Video>;

export const getVideo = (id: string): Video => videosById[id] ?? videos[0];

/** Feed pools — in Phase 7 these become real candidate pools from the ranking service. */
export const forYouVideos: Video[] = videos;

export const followingVideos: Video[] = videos
  .filter((v) => v.author.isFollowing)
  .map((v) => ({ ...v, feedSource: 'following' as const }));

export const trendingVideos: Video[] = [...videos]
  .sort((a, b) => b.stats.views - a.stats.views)
  .map((v) => ({ ...v, feedSource: 'trending' as const }));

export const myVideos: Video[] = videos.filter((v) => v.author.id === currentUser.id);

export const likedVideos: Video[] = videos.filter((v) => v.liked);

export const savedVideos: Video[] = videos.filter((v) => v.saved);

export const videosByCategory = (category: string): Video[] =>
  videos.filter((v) => v.category.toLowerCase() === category.toLowerCase());
